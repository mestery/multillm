# Render llm-router/config.yaml from BACKEND_* environment variables in .env.
# Usage: sh scripts/render-config.sh

set -e

ENV_FILE="${ENV_FILE:-.env}"
OUT="${CONFIG_OUT:-llm-router/config.yaml}"

if [ ! -f "$ENV_FILE" ]; then
  echo "Error: $ENV_FILE not found. Copy .env.example to $ENV_FILE and configure." >&2
  exit 1
fi

# Source .env (handle comments and empty lines)
eval "$(grep -v '^\s*#' "$ENV_FILE" | grep -v '^\s*$' | sed "s/^/export /")"

OUT_DIR="$(dirname "$OUT")"
mkdir -p "$OUT_DIR"

cat > "$OUT" <<'HEADER'
# LiteLLM proxy configuration for MultiLLM.
# Generated by scripts/render-config.sh from .env (BACKEND_* vars).
# Do not edit by hand; the file is re-rendered on every
# 'docker compose up' (runtime edits are overwritten on the next start).

HEADER

echo "model_list:" >> "$OUT"

N=1
while true; do
  # Use eval to get the value of BACKEND_N_TYPE
  eval "TYPE=\$BACKEND_${N}_TYPE" || true
  [ -z "$TYPE" ] && break

  # Get other variables using eval
  eval "HOST=\$BACKEND_${N}_HOST" || true
  [ -z "$HOST" ] && HOST="host.docker.internal"

  eval "PORT=\$BACKEND_${N}_PORT" || true
  [ -z "$PORT" ] && PORT="$([ "$TYPE" = "lmstudio" ] && echo 1234 || echo 8000)"

  eval "NAME=\$BACKEND_${N}_NAME" || true
  [ -z "$NAME" ] && NAME="${TYPE}-${PORT}"

  eval "API_KEY=\$BACKEND_${N}_API_KEY" || true
  [ -z "$API_KEY" ] && API_KEY="placeholder"

  cat >> "$OUT" <<EOF
  # Backend $N: $TYPE ($NAME) — $HOST:$PORT
  - model_name: $NAME
    litellm_params:
      model: openai/$NAME
      api_base: http://$HOST:$PORT/v1
      api_key: $API_KEY

EOF

  N=$((N + 1))
done

echo "Generated $OUT with $((N - 1)) backend(s)."
