# Render llm-router/config.yaml from BACKEND_* environment variables in .env.
# Usage: sh scripts/render-config.sh

set -e

ENV_FILE="${ENV_FILE:-.env}"
OUT="${CONFIG_OUT:-llm-router/config.yaml}"

if [ ! -f "$ENV_FILE" ]; then
  echo "Error: $ENV_FILE not found. Copy .env.example to $ENV_FILE and configure." >&2
  exit 1
fi

# Read a single KEY=VALUE from $ENV_FILE without eval. The value is treated
# strictly as data (never executed), so a hostile .env cannot inject shell
# commands. Prints the value with inline comments and surrounding quotes
# stripped, or nothing if the key is absent.
env_get() {
  _eg_line=$(grep -E "^[ \t]*$1=" "$ENV_FILE" | head -n 1) || true
  [ -z "$_eg_line" ] && return 0
  _eg_val=${_eg_line#*=}
  _eg_val=$(printf '%s' "$_eg_val" | sed -E 's/[ \t]+#.*$//; s/\r$//; s/^[ \t]+//; s/[ \t]+$//')
  case "$_eg_val" in
    \"*\") _eg_val=${_eg_val#\"}; _eg_val=${_eg_val%\"} ;;
    \'*\') _eg_val=${_eg_val#\'}; _eg_val=${_eg_val%\'} ;;
  esac
  printf '%s' "$_eg_val"
}

OUT_DIR="$(dirname "$OUT")"
mkdir -p "$OUT_DIR"

cat > "$OUT" <<'HEADER'
# LiteLLM proxy configuration for MultiLLM.
# Generated by scripts/render-config.sh from .env (BACKEND_* vars).
# Do not edit by hand; the file is re-rendered on every
# 'docker compose up' (runtime edits are overwritten on the next start).

HEADER

echo "model_list:" >> "$OUT"

N=1
while true; do
  TYPE=$(env_get "BACKEND_${N}_TYPE")
  [ -z "$TYPE" ] && break

  HOST=$(env_get "BACKEND_${N}_HOST")
  [ -z "$HOST" ] && HOST="host.docker.internal"

  PORT=$(env_get "BACKEND_${N}_PORT")
  if [ -z "$PORT" ]; then
    case "$TYPE" in
      lmstudio)   PORT=1234 ;;
      llamaserver) PORT=8080 ;;
      *)          PORT=8000 ;;
    esac
  fi

  NAME=$(env_get "BACKEND_${N}_NAME")
  [ -z "$NAME" ] && NAME="${TYPE}-${PORT}"

  API_KEY=$(env_get "BACKEND_${N}_API_KEY")
  [ -z "$API_KEY" ] && API_KEY="placeholder"

  # llamaserver runs as a Docker service inside the compose network;
  # other backends run natively on the host and are reached via host.docker.internal.
  if [ -z "$HOST" ] || [ "$HOST" = "host.docker.internal" ]; then
    if [ "$TYPE" = "llamaserver" ]; then
      HOST="llama-server"
    fi
  fi

  cat >> "$OUT" <<EOF
  # Backend $N: $TYPE ($NAME) — $HOST:$PORT
  - model_name: $NAME
    litellm_params:
      model: openai/$NAME
      api_base: http://$HOST:$PORT/v1
      api_key: $API_KEY

EOF

  N=$((N + 1))
done

echo "Generated $OUT with $((N - 1)) backend(s)."
