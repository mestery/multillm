# Render llm-router/config.yaml from BACKEND_* environment variables.
#
# Backends are declared in .env as BACKEND_<N>_* (N = 1..MAX_BACKENDS,
# contiguous starting at 1):
#   BACKEND_<N>_TYPE             mtplx | lmstudio | omlx   (required)
#   BACKEND_<N>_HOST             default: host.docker.internal
#   BACKEND_<N>_PORT             default: 8000 (mtplx/omlx), 1234 (lmstudio)
#   BACKEND_<N>_NAME             default: <type>-<port>
#   BACKEND_<N>_API_KEY          default: placeholder accepted by the backend
#   BACKEND_<N>_CONTEXT_LENGTH   default: 131072
#
# ROUTER_API_KEY (required) is the key clients such as Open WebUI use.
#
# POSIX sh: runs on the host (sh scripts/render-config.sh) and inside the
# alpine llmrouter-init container (see docker-compose.yml).

set -eu

OUT="${CONFIG_OUT:-llm-router/config.yaml}"
MAX="${MAX_BACKENDS:-8}"
: "${ROUTER_API_KEY:?ROUTER_API_KEY is required (set it in .env)}"

default_port() {
  case "$1" in
    mtplx) echo 8000 ;;
    lmstudio) echo 1234 ;;
    omlx) echo 8000 ;;
  esac
}

default_key() {
  case "$1" in
    mtplx) echo mtplx ;;
    lmstudio) echo lm-studio ;;
    omlx) echo omlx ;;
  esac
}

# get VARNAME: print a (possibly unset) variable by name. Names are built
# here from our own integer loop index, never from user input.
get() {
  eval "printf '%s' \"\${$1:-}\""
}

mkdir -p "$(dirname "$OUT")"

{
  echo "# Generated by scripts/render-config.sh from .env (BACKEND_* vars)."
  echo "# Do not edit by hand; the file is re-rendered on every"
  echo "# 'docker compose up' (runtime edits via the LLMRouter UI are"
  echo "# overwritten on the next start)."
  echo "version: 1"
  echo ""
  echo "api_keys:"
  echo '  - id: "1"'
  echo '    alias: "router"'
  printf '    key: "%s"\n' "$ROUTER_API_KEY"
  echo '    limit: -1'
  echo '    expires_at: -1'
  echo "model_groups:"
} > "$OUT"

count=0
i=1
while [ "$i" -le "$MAX" ]; do
  btype="$(get "BACKEND_${i}_TYPE")"
  [ -n "$btype" ] || break

  case "$btype" in
    mtplx | lmstudio | omlx) ;;
    *) echo "BACKEND_${i}_TYPE: unknown backend type '$btype' (expected mtplx, lmstudio, or omlx)" >&2
       exit 1 ;;
  esac

  bhost="$(get "BACKEND_${i}_HOST")";    [ -n "$bhost" ] || bhost="host.docker.internal"
  bport="$(get "BACKEND_${i}_PORT")";    [ -n "$bport" ] || bport="$(default_port "$btype")"
  bname="$(get "BACKEND_${i}_NAME")";    [ -n "$bname" ] || bname="${btype}-${bport}"
  bkey="$(get "BACKEND_${i}_API_KEY")";  [ -n "$bkey" ] || bkey="$(default_key "$btype")"
  bctx="$(get "BACKEND_${i}_CONTEXT_LENGTH")"; [ -n "$bctx" ] || bctx=131072

  case "$bport" in
    '' | *[!0-9]*) echo "BACKEND_${i}_PORT: '$bport' is not a valid port" >&2; exit 1 ;;
  esac

  {
    printf '  - name: "%s"\n' "$bname"
    echo '    api_key_id: "1"'
    echo "    endpoints:"
    printf '      - id: "%s"\n' "$i"
    echo '        type: "openai"'
    printf '        base_url: "http://%s:%s/v1"\n' "$bhost" "$bport"
    echo '        endpoint: ""'
    printf '        api_key: "%s"\n' "$bkey"
    printf '        context_length: %s\n' "$bctx"
    echo '        model_names: []'
    echo '        load_balance: "round_robin"'
    echo '        load_balancing_weight: 1'
  } >> "$OUT"

  count=$((count + 1))
  i=$((i + 1))
done

if [ "$count" -eq 0 ]; then
  echo "No backends configured: set at least one BACKEND_<N>_TYPE in .env" >&2
  exit 1
fi

echo "render-config: wrote $OUT with $count backend(s)" >&2